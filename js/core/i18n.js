const CATALOGOS = { es: ES, en: EN };

let idiomaActual = detectarIdioma();

function detectarIdioma() {
  // 1. Lo que la persona haya elegido a mano manda siempre.
  try {
    const guardado = localStorage.getItem(STORAGE_KEYS.idioma);
    if (guardado && CATALOGOS[guardado]) return guardado;
  } catch { /* almacenamiento bloqueado */ }

  // 2. El centro de oficinas está en México y se atiende en español: el
  //    idioma de la app es el español salvo que el navegador esté
  //    claramente en inglés. Antes bastaba con un navegador en inglés de
  //    fábrica para que toda la interfaz saliera en otro idioma.
  const nav = (typeof navigator !== "undefined" && (navigator.language || "")).slice(0, 2).toLowerCase();
  if (nav === "en") return "en";
  return APP.defaultLocale;
}

export function getIdioma() { return idiomaActual; }

export function setIdioma(code) {
  if (!CATALOGOS[code] || code === idiomaActual) return;
  idiomaActual = code;
  try { localStorage.setItem(STORAGE_KEYS.idioma, code); } catch { /* ignora */ }
  if (typeof document !== "undefined") document.documentElement.lang = code;
  emit(EV.IDIOMA_CAMBIO, code);
}

/** Traduce una clave. Acepta valores para interpolar {llaves}. */
export function t(clave, vars) {
  const cat = CATALOGOS[idiomaActual] || ES;
  let texto = cat[clave];
  if (texto == null) texto = ES[clave];
  if (texto == null) return clave;
  if (!vars) return texto;
  return texto.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

if (typeof document !== "undefined") document.documentElement.lang = idiomaActual;

export default { t, setIdioma, getIdioma, IDIOMAS };
